package main

import (
	"bytes"
	"fmt"
	"go/format"
	"reflect"
	"strings"
	"time"

	"github.com/nethinwei/sql-mcp-server/core/config"
)

const specPath = "core/config/spec_gen.go"

// GenerateSpec writes core/config/spec_gen.go: for each struct of the
// configuration, its Spec (what an author wrote: every field optional, nil
// when unset), the conversion of a Spec into the Config it means before
// defaults (config), and of a Config built in code back into a Spec (spec).
func GenerateSpec() ([]byte, error) {
	g := &specGen{seen: map[reflect.Type]bool{}}
	g.collect(reflect.TypeFor[config.Config]())
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/schemagen; DO NOT EDIT.\n\npackage config\n\n")
	b.WriteString("import (\n\t\"maps\"\n\t\"slices\"\n\t\"time\"\n)\n\n")
	b.WriteString("var _ time.Duration // durations are fields of some Specs\n\n")
	for _, t := range g.types {
		if err := g.writeType(&b, t); err != nil {
			return nil, err
		}
	}
	return format.Source(b.Bytes())
}

type specGen struct {
	types []reflect.Type
	seen  map[reflect.Type]bool
}

var durationT = reflect.TypeFor[time.Duration]()

func inConfig(t reflect.Type) bool {
	return t.PkgPath() == reflect.TypeFor[config.Config]().PkgPath()
}

// collect lists the configuration's struct types, depth first.
func (g *specGen) collect(t reflect.Type) {
	switch t.Kind() {
	case reflect.Pointer, reflect.Slice, reflect.Map:
		g.collect(t.Elem())
		return
	case reflect.Struct:
	default:
		return
	}
	if !inConfig(t) || g.seen[t] {
		return
	}
	g.seen[t] = true
	g.types = append(g.types, t)
	for i := range t.NumField() {
		if f := t.Field(i); f.IsExported() {
			g.collect(f.Type)
		}
	}
}

// specName is the Spec of a configuration struct: ServerConfig is
// ServerSpec, Config is Spec, MCPFlags is MCPFlagsSpec.
func specName(t reflect.Type) string {
	if t.Name() == "Config" {
		return "Spec"
	}
	if name, ok := strings.CutSuffix(t.Name(), "Config"); ok {
		return name + "Spec"
	}
	return t.Name() + "Spec"
}

// goType is t as written in package config.
func goType(t reflect.Type) string {
	switch {
	case t == durationT:
		return "time.Duration"
	case t.Kind() == reflect.Interface:
		return "any"
	case t.Name() != "" && inConfig(t):
		return t.Name()
	case t.Name() != "":
		return t.String()
	case t.Kind() == reflect.Pointer:
		return "*" + goType(t.Elem())
	case t.Kind() == reflect.Slice:
		return "[]" + goType(t.Elem())
	case t.Kind() == reflect.Map:
		return "map[" + goType(t.Key()) + "]" + goType(t.Elem())
	}
	return t.String()
}

func isStruct(t reflect.Type) bool {
	return t.Kind() == reflect.Struct && t != durationT && inConfig(t)
}

// specType is the Spec type of a field of type t.
func specType(t reflect.Type) string {
	switch {
	case isStruct(t):
		return "*" + specName(t)
	case t.Kind() == reflect.Pointer && isStruct(t.Elem()):
		return "*" + specName(t.Elem())
	case t.Kind() == reflect.Pointer:
		return goType(t)
	case t.Kind() == reflect.Slice && isStruct(t.Elem()):
		return "List[" + specName(t.Elem()) + "]"
	case t.Kind() == reflect.Slice:
		return "List[" + goType(t.Elem()) + "]"
	case t.Kind() == reflect.Map && isStruct(t.Elem()):
		return "Map[" + goType(t.Key()) + ", " + specName(t.Elem()) + "]"
	case t.Kind() == reflect.Map && t.Elem().Kind() == reflect.Interface:
		// Free form (a row filter, a subject): YAML decodes the maps nested
		// in it as the type of the outer one, which must stay map[string]any.
		return goType(t)
	case t.Kind() == reflect.Map:
		return "Map[" + goType(t.Key()) + ", " + goType(t.Elem()) + "]"
	case t.Kind() == reflect.Interface:
		return "any"
	}
	return "*" + goType(t)
}

// presence is how a struct records which of its fields were written, as
// ApplyDefaults reads it: a map of present YAML names, a flag that the
// struct itself was written, and a flag per field (field name → flag).
type presence struct {
	fields  bool
	written bool
	flags   map[string]string
}

func presenceOf(t reflect.Type) presence {
	p := presence{flags: map[string]string{}}
	for i := range t.NumField() {
		f := t.Field(i)
		switch {
		case f.IsExported():
		case f.Name == "present" && f.Type.Kind() == reflect.Map:
			p.fields = true
		case f.Name == "present" && f.Type.Kind() == reflect.Bool:
			p.written = true
		case strings.HasSuffix(f.Name, "Set") && f.Type.Kind() == reflect.Bool:
			for j := range t.NumField() {
				if g := t.Field(j); g.IsExported() && strings.EqualFold(g.Name, strings.TrimSuffix(f.Name, "Set")) {
					p.flags[g.Name] = f.Name
				}
			}
		}
	}
	return p
}

func yamlName(f reflect.StructField) string {
	name, _, _ := strings.Cut(f.Tag.Get("yaml"), ",")
	return name
}

func (g *specGen) writeType(b *bytes.Buffer, t reflect.Type) error {
	name := specName(t)
	fmt.Fprintf(b, "// %s is a %s as written: a nil field was not.\n", name, t.Name())
	fmt.Fprintf(b, "type %s struct {\n", name)
	for i := range t.NumField() {
		f := t.Field(i)
		yn := yamlName(f)
		if !f.IsExported() || yn == "" || yn == "-" {
			continue
		}
		fmt.Fprintf(b, "\t%s %s `yaml:\"%s,omitempty\" json:\"%s,omitempty\"`\n", f.Name, specType(f.Type), yn, yn)
	}
	b.WriteString("}\n\n")
	if err := g.writeConfig(b, t); err != nil {
		return err
	}
	g.writeCanonical(b, t)
	return g.writeSpec(b, t)
}

func omitEmpty(f reflect.StructField) bool {
	_, opts, _ := strings.Cut(f.Tag.Get("yaml"), ",")
	return strings.Contains(opts, "omitempty")
}

// writeCanonical writes canonical, which unsets what is written but means
// unset: a zero, or an empty list or map, where the struct omits it (an
// older encoding wrote some), so two payloads saying the same compare equal.
// It writes only what it changes, and reports whether it did: a spec
// canonical already (as decoded) is only read, so callers may share it.
func (g *specGen) writeCanonical(b *bytes.Buffer, t reflect.Type) {
	fmt.Fprintf(b, "func (s *%s) canonical() (changed bool) {\n", specName(t))
	for i := range t.NumField() {
		f := t.Field(i)
		yn := yamlName(f)
		if !f.IsExported() || yn == "" || yn == "-" {
			continue
		}
		ft := f.Type
		switch {
		case isStruct(ft) || ft.Kind() == reflect.Pointer && isStruct(ft.Elem()):
			fmt.Fprintf(b, "\tif s.%[1]s != nil && s.%[1]s.canonical() {\n\t\tchanged = true\n\t}\n", f.Name)
		case (ft.Kind() == reflect.Slice || ft.Kind() == reflect.Map) && isStruct(ft.Elem()):
			fmt.Fprintf(b, "\tfor k, v := range s.%[1]s {\n\t\tif v.canonical() {\n\t\t\ts.%[1]s[k], changed = v, true\n"+
				"\t\t}\n\t}\n", f.Name)
			if omitEmpty(f) {
				writeUnsetEmpty(b, f.Name)
			}
		case (ft.Kind() == reflect.Slice || ft.Kind() == reflect.Map) && omitEmpty(f):
			writeUnsetEmpty(b, f.Name)
		case ft.Kind() == reflect.Pointer || ft.Kind() == reflect.Slice || ft.Kind() == reflect.Map ||
			ft.Kind() == reflect.Interface || !omitEmpty(f):
		default:
			fmt.Fprintf(b, "\tif s.%[1]s != nil && *s.%[1]s == *new(%[2]s) {\n\t\ts.%[1]s, changed = nil, true\n\t}\n",
				f.Name, goType(ft))
		}
	}
	b.WriteString("\treturn changed\n}\n\n")
}

// writeUnsetEmpty unsets field when it is written empty.
func writeUnsetEmpty(b *bytes.Buffer, field string) {
	fmt.Fprintf(b, "\tif s.%[1]s != nil && len(s.%[1]s) == 0 {\n\t\ts.%[1]s, changed = nil, true\n\t}\n", field)
}

// writeConfig writes the conversion of a Spec into its struct before
// defaults, with the presence ApplyDefaults reads.
func (g *specGen) writeConfig(b *bytes.Buffer, t reflect.Type) error {
	p := presenceOf(t)
	fmt.Fprintf(b, "func (s %s) config() %s {\n\tvar out %s\n", specName(t), t.Name(), t.Name())
	if p.fields {
		b.WriteString("\tout.present = map[string]bool{}\n")
	}
	if p.written {
		b.WriteString("\tout.present = true\n")
	}
	for i := range t.NumField() {
		f := t.Field(i)
		yn := yamlName(f)
		if !f.IsExported() || yn == "" || yn == "-" {
			continue
		}
		conv, err := toConfig(f.Name, f.Type)
		if err != nil {
			return fmt.Errorf("%s.%s: %w", t.Name(), f.Name, err)
		}
		b.WriteString(conv)
		if p.fields && f.Type.Kind() != reflect.Interface {
			fmt.Fprintf(b, "\tif s.%s != nil {\n\t\tout.present[%q] = true\n\t}\n", f.Name, yn)
		}
		if flag, ok := p.flags[f.Name]; ok {
			fmt.Fprintf(b, "\tout.%s = s.%s != nil\n", flag, f.Name)
		}
	}
	b.WriteString("\treturn out\n}\n\n")
	return nil
}

func toConfig(name string, t reflect.Type) (string, error) {
	switch {
	case isStruct(t):
		return fmt.Sprintf("\tif s.%[1]s != nil {\n\t\tout.%[1]s = s.%[1]s.config()\n\t}\n", name), nil
	case t.Kind() == reflect.Pointer && isStruct(t.Elem()):
		return fmt.Sprintf("\tif s.%[1]s != nil {\n\t\tout.%[1]s = ptr(s.%[1]s.config())\n\t}\n", name), nil
	case t.Kind() == reflect.Pointer:
		return fmt.Sprintf("\tif s.%[1]s != nil {\n\t\tout.%[1]s = ptr(*s.%[1]s)\n\t}\n", name), nil
	case t.Kind() == reflect.Slice && isStruct(t.Elem()):
		return fmt.Sprintf("\tif s.%[1]s != nil {\n\t\tout.%[1]s = make(%[2]s, len(s.%[1]s))\n"+
			"\t\tfor i, v := range s.%[1]s {\n\t\t\tout.%[1]s[i] = v.config()\n\t\t}\n\t}\n", name, goType(t)), nil
	case t.Kind() == reflect.Map && isStruct(t.Elem()):
		return fmt.Sprintf("\tif s.%[1]s != nil {\n\t\tout.%[1]s = make(%[2]s, len(s.%[1]s))\n"+
			"\t\tfor k, v := range s.%[1]s {\n\t\t\tout.%[1]s[k] = v.config()\n\t\t}\n\t}\n", name, goType(t)), nil
	case t.Kind() == reflect.Slice:
		// Copied one level deep: normalizing the configuration replaces the
		// elements in place, never what is inside them, so inner lists and
		// maps (uniqueKeys' keys, filters' values) stay shared with the Spec.
		return fmt.Sprintf("\tout.%[1]s = slices.Clone(%[2]s(s.%[1]s))\n", name, goType(t)), nil
	case t.Kind() == reflect.Map:
		return fmt.Sprintf("\tout.%[1]s = maps.Clone(%[2]s(s.%[1]s))\n", name, goType(t)), nil
	case t.Kind() == reflect.Interface:
		return fmt.Sprintf("\tout.%[1]s = s.%[1]s\n", name), nil
	case t.Kind() == reflect.Struct:
		return "", fmt.Errorf("unsupported struct %s", t)
	}
	return fmt.Sprintf("\tif s.%[1]s != nil {\n\t\tout.%[1]s = *s.%[1]s\n\t}\n", name), nil
}

// writeSpec writes the conversion of a struct built in code into its Spec,
// as ApplyDefaults reads it: a field with its own presence flag is written
// when the flag says so; one a presence map tracks, when present or not zero;
// any other, when not zero (zero is unset there).
func (g *specGen) writeSpec(b *bytes.Buffer, t reflect.Type) error {
	p := presenceOf(t)
	fmt.Fprintf(b, "func (c %s) spec() %s {\n\tvar out %s\n", t.Name(), specName(t), specName(t))
	for i := range t.NumField() {
		f := t.Field(i)
		yn := yamlName(f)
		if !f.IsExported() || yn == "" || yn == "-" {
			continue
		}
		var cond string
		switch flag, ok := p.flags[f.Name]; {
		case ok:
			cond = "c." + flag
		case p.fields:
			cond = fmt.Sprintf("c.present[%q]", yn)
		case p.written:
			cond = "c.present"
		}
		b.WriteString(toSpec(f.Name, f.Type, cond))
	}
	b.WriteString("\treturn out\n}\n\n")
	return nil
}

func toSpec(name string, t reflect.Type, cond string) string {
	switch {
	case isStruct(t):
		return fmt.Sprintf("\tif v := c.%[1]s.spec(); !isZero(v) {\n\t\tout.%[1]s = &v\n\t}\n", name)
	case t.Kind() == reflect.Pointer && isStruct(t.Elem()):
		return fmt.Sprintf("\tif c.%[1]s != nil {\n\t\tout.%[1]s = ptr(c.%[1]s.spec())\n\t}\n", name)
	case t.Kind() == reflect.Pointer:
		return fmt.Sprintf("\tif c.%[1]s != nil {\n\t\tout.%[1]s = ptr(*c.%[1]s)\n\t}\n", name)
	case t.Kind() == reflect.Slice && isStruct(t.Elem()):
		return fmt.Sprintf("\tif c.%[1]s != nil {\n\t\tout.%[1]s = make(%[2]s, len(c.%[1]s))\n"+
			"\t\tfor i, v := range c.%[1]s {\n\t\t\tout.%[1]s[i] = v.spec()\n\t\t}\n\t}\n", name, specType(t))
	case t.Kind() == reflect.Map && isStruct(t.Elem()):
		return fmt.Sprintf("\tif c.%[1]s != nil {\n\t\tout.%[1]s = make(%[2]s, len(c.%[1]s))\n"+
			"\t\tfor k, v := range c.%[1]s {\n\t\t\tout.%[1]s[k] = v.spec()\n\t\t}\n\t}\n", name, specType(t))
	case t.Kind() == reflect.Slice || t.Kind() == reflect.Map:
		// Shared, not copied: SpecOf's Spec and the configuration alias it.
		return fmt.Sprintf("\tout.%[1]s = %[2]s(c.%[1]s)\n", name, specType(t))
	case t.Kind() == reflect.Interface:
		return fmt.Sprintf("\tout.%[1]s = c.%[1]s\n", name)
	case strings.HasPrefix(cond, "c.present"):
		return fmt.Sprintf("\tif %[2]s || c.%[1]s != *new(%[3]s) {\n\t\tout.%[1]s = ptr(c.%[1]s)\n\t}\n",
			name, cond, goType(t))
	case cond != "":
		return fmt.Sprintf("\tif %[2]s {\n\t\tout.%[1]s = ptr(c.%[1]s)\n\t}\n", name, cond)
	}
	return fmt.Sprintf("\tout.%[1]s = set(c.%[1]s)\n", name)
}
